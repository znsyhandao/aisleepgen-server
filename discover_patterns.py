# =============================================
# 工具函数
# =============================================

def _load_log():
    if not os.path.exists(EXPERIMENT_LOG):
        return []
    with open(EXPERIMENT_LOG, 'r', encoding='utf-8') as f:
        data = json.load(f)
    return data.get('experiments', [])


def _is_covered_by_existing(keywords):
    """检查关键词是否已被现有检测器覆盖"""
    for fname in os.listdir(DETECTORS_DIR):
        if not fname.endswith('.py') or fname.startswith('__') or fname == 'base.py':
            continue
        with open(os.path.join(DETECTORS_DIR, fname), 'r', encoding='utf-8') as f:
            content = f.read()
        if any(kw in content for kw in keywords):
            return True
    return False


def _find_observation_records():
    """扫描已生成的检测器，找出还处于观察期的"""
    observing = []
    for fname in os.listdir(DETECTORS_DIR):
        if not fname.endswith('.py') or fname.startswith('__') or fname == 'base.py':
            continue
        fpath = os.path.join(DETECTORS_DIR, fname)
        with open(fpath, 'r', encoding='utf-8') as f:
            content = f.read()
        # 查找标记
        m = re.search(r'Auto-generated by discover_patterns.py at ([\d-]+ [\d:]+)', content)
        if m:
            gen_time = datetime.strptime(m.group(1), '%Y-%m-%d %H:%M')
            elapsed = (datetime.now() - gen_time).total_seconds() / 86400
            observing.append((fname, gen_time, elapsed))
    return observing


# =============================================
# 第2步：回测验证
# =============================================

def _backtest(keywords):
    """
    用历史 experiment_log 回测候选模式。
    检查：命中该模式的对话中，有多少是"真正相关"的。
    
    真正相关的判断：用户消息中包含该关键词，且AI回复长度>20（表明有实质内容）
    误报的判断：命中但AI回复很短（简单回应）
    
    返回: (hits, false_positives, precision)
    """
    exps = _load_log()
    if not exps:
        return 0, 0, 0.0
    
    hits = 0
    false_positives = 0
    
    for e in exps:
        if e.get('intervention_type') != 'chat':
            continue
        msg = e.get('hypothesis', '')
        if not msg:
            continue
        
        # 检查是否命中关键词
        matched = False
        for kw in keywords:
            if kw in msg:
                matched = True
                break
        
        if not matched:
            continue
        
        hits += 1
        
        # 判断是否为"真命中"：有实质回复
        # 从 outcome/observation 中取回复相关信息
        outcome = e.get('outcome', {})
        if isinstance(outcome, dict):
            positive = outcome.get('positive', False)
            detail = str(outcome.get('detail', ''))
            if not positive and 'reply_len=0' in detail:
                false_positives += 1
        elif outcome is None:
            false_positives += 1
    
    precision = (hits - false_positives) / max(hits, 1)
    return hits, false_positives, precision


