# 第3步：生成实验性检测器
# =============================================

def _generate_detector(name, keywords, protocol, confidence):
    """生成检测器文件，标记为实验性"""
    safe_name = name.replace(' ', '_').replace('/', '_')
    safe_name = re.sub(r'[^\u4e00-\u9fff\w_]', '', safe_name)
    filename = f'detector_{safe_name}.py'
    filepath = os.path.join(DETECTORS_DIR, filename)
    
    if os.path.exists(filepath):
        print(f'    -> 跳过（已存在）: {filename}')
        return None
    
    kw_str = ', '.join(repr(k) for k in keywords)
    now_str = datetime.now().strftime('%Y-%m-%d %H:%M')
    
    code = f'''# -*- coding: utf-8 -*-
# Auto-generated by discover_patterns.py at {now_str}
# Pattern: {name}
# Status: EXPERIMENTAL — observing for {OBSERVATION_DAYS} days

from . import SignalDetector

_KEYWORDS = [{kw_str}]


class Detector(SignalDetector):
    protocol = '{protocol}'
    
    def detect(self, msg):
        for kw in _KEYWORDS:
            if kw in msg:
                return {confidence}
        return 0.0
    
    def get_keywords(self):
        return list(_KEYWORDS)
'''
    
    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(code)
    print(f'    -> 创建实验性检测器: {filename}')
    return filename


def _register_detector(filename):
    """注册到 __init__.py，放在列表末尾（最低优先级）"""
    init_path = os.path.join(DETECTORS_DIR, '__init__.py')
    with open(init_path, 'r', encoding='utf-8') as f:
        lines = f.readlines()
    
    mod_name = filename[:-3]
    import_line = f'from .{mod_name} import Detector as _{mod_name}\n'
    
    # 跳过已注册
    if import_line in lines:
        return True
    
    # 加在最后一条 import 之后
    last_import = -1
    for i, line in enumerate(lines):
        if line.startswith('from .detector_') and 'others' not in line:
            last_import = i
    
    if last_import >= 0:
        lines.insert(last_import + 1, import_line)
    
    # 加在 ALL_DETECTORS 列表末尾（最低优先级）
    list_end = None
    for i, line in enumerate(lines):
        l = line.strip()
        if l == ']' and i > max(last_import, 0):
            list_end = i
            break
    
    if list_end is not None:
        lines.insert(list_end, f'    _{mod_name}(),\n')
    
    with open(init_path, 'w', encoding='utf-8') as f:
        f.writelines(lines)
    
    print(f'    -> 注册到 __init__.py（最低优先级）')
    return True


# =============================================
# 第4步：观察期管理
# =============================================

def _promote_observing():
    """检查观察期满的检测器，决定是否正式激活"""
    records = _find_observation_records()
    if not records:
        print('  (没有处于观察期的检测器)')
        return
    
    now = datetime.now()
    
    for fname, gen_time, elapsed in records:
        status = f'创建于 {gen_time.strftime("%m-%d %H:%M")}（{elapsed:.1f}天前）'
        
        if elapsed < OBSERVATION_DAYS:
            remaining = OBSERVATION_DAYS - elapsed
            print(f'  [...] {fname}: {status} — 观察中（还需 {remaining:.1f}天）')
            continue
        
        # 观察期满 → 正式激活
        # 目前只是移除"EXPERIMENTAL"标记
        fpath = os.path.join(DETECTORS_DIR, fname)
        with open(fpath, 'r', encoding='utf-8') as f:
            content = f.read()
        
        content = content.replace(
            'Status: EXPERIMENTAL — observing for 7 days',
            'Status: ACTIVE — promoted after observation period'
        )
        
        with open(fpath, 'w', encoding='utf-8') as f:
            f.write(content)
        
        print(f'  [OK] {fname}: {status} — **观察期满，正式激活**')


# =============================================
# 验证
