def main():
    print('=' * 54)
    print('  discover_patterns.py v3 -- 安全模式发现器')
    print(f'  {datetime.now().strftime("%Y-%m-%d %H:%M")}')
    print(f'  精确率门槛: {PRECISION_THRESHOLD*100:.0f}% | 观察期: {OBSERVATION_DAYS}天')
    print('=' * 54)
    
    # 模式A：促进观察中的检测器
    if '--promote' in sys.argv:
        print('')
        print('>> 检查观察期状态...')
        _promote_observing()
        return
    
    # 模式B：发现+生成新检测器
    print('')
    print('>> 扫描候选模式...')
    
    accepted = []
    for pattern in KNOWN_PATTERNS:
        name = pattern['name']
        kws = pattern['keywords']
        protocol = pattern['protocol']
        confidence = pattern['confidence']
        
        # 第1步：检查是否已被现有检测器覆盖
        if _is_covered_by_existing(kws):
            print(f'  [SKIP] {name} — 已覆盖')
            continue
        
        # 第2步：回测验证
        hits, fps, precision = _backtest(kws)
        print(f'  [BACKTEST] {name}: 命中{hits}次, 误报{fps}次, 精确率{precision*100:.0f}%', end='')
        
        if hits < REQUIRED_HITS:
            print(' → [NO] 未达到最低命中次数')
            continue
        
        if precision < PRECISION_THRESHOLD:
            print(f' → [NO] 精确率低于{PRECISION_THRESHOLD*100:.0f}%')
            continue
        
        print(' → [OK] 通过')
        accepted.append(pattern)
    
    if not accepted:
        print('\n[DONE] 没有通过验证的候选模式')
        return
    
    # 第3步：生成+注册新检测器
    print(f'\n>>  生成 {len(accepted)} 个实验性检测器...')
    
    for pattern in accepted:
        filename = _generate_detector(
            pattern['name'],
            pattern['keywords'],
            pattern['protocol'],
            pattern['confidence'],
        )
        if filename:
            _register_detector(filename)
    
    # 第4步：验证编译
    print('\n>>  验证编译...')
    _verify_compile()
    
    print(f'\n[DONE] 已生成 {len(accepted)} 个实验性检测器')
    print(f'这些检测器已在最低优先级注册。观察{OBSERVATION_DAYS}天后运行:')
    print(f'  python discover_patterns.py --promote')


if __name__ == '__main__':
    main()
