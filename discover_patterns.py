def _verify_compile():
    import py_compile
    try:
        py_compile.compile('dp_router.py', doraise=True)
        print('  [OK] dp_router.py 编译通过')
    except py_compile.PyCompileError as e:
        print(f'  [FAIL] 编译失败: {e}')
        return False
    return True


